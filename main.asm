        add di, 4
        mov word [es:di + 16], 0x8FF0   ; outer half of lane line
        mov word [es:di + 18], 0x8FF1   ; inner half of lane line
        pop di
        skip_left_lane:

        pop di
        pop cx
        add di, 160
        add word [bp - 6], 1
        loop road_loop

    pop di
    pop es
    pop dx
    pop cx
    pop bx
    pop ax
    mov sp, bp
    pop bp
    ret

