clear_screen:
    push ax
    push cx
    push es
    push di
    
    mov ax, 0xb800
    mov es, ax
    mov cx, 2000
    mov di, 0
    mov ax, 0x0720
    
    cld
    rep stosw
    
    pop di
    pop es
    pop cx
    pop ax
    ret

