        mov di, [bp - 4]
        sub di, 2
        mov cx, [bp - 6]

        std
        rep stosw
        mov word [es:di], 0x8FF1
        mov word [es:di - 2], 0xAFF0

        ; Draw dashed left lane 8 cols inside the left edge
        mov bx, [esp + 2] ; peek outer CX
        test bl, 2
