update_fuel_bar:
    push ax
    push bx
    push cx
    push di
    push es

    mov ax, 0xB800
    mov es, ax
    mov di, 3754 ; 23*160 + 37*2 (first inner cell)
    cld

    ; Load and clamp fuel_level to 0..18
    xor ax, ax
    mov al, [fuel_level]
    cmp al, 18
    jbe update_fuel_level_ok
    mov al, 18
    update_fuel_level_ok:
        mov bl, al ; BL = filled block count (0..18)
    
        ; Pick bar color based on remaining fuel
        mov ah, 0x0A ; Bright Green on Black (> 9 blocks)
        cmp bl, 9
        ja update_fuel_color_ready
        mov ah, 0x0E ; Yellow on Black (5..9 blocks)
        cmp bl, 4
        ja update_fuel_color_ready
        mov ah, 0x0C ; Bright Red on Black (0..4 blocks)

    update_fuel_color_ready:
        ; Draw filled fuel blocks
        xor cx, cx
        mov cl, bl
        jcxz update_fuel_draw_empty
        mov al, 0xDB ; Solid full block
        rep stosw

    update_fuel_draw_empty:
        ; Fill remaining cells up to 18 with pure black spaces
        mov cl, 18
        sub cl, bl
        jcxz update_fuel_done
        mov ax, 0x0720 ; Space on Pure Black
        rep stosw

    update_fuel_done:
        pop es
        pop di
        pop cx
        pop bx
        pop ax
        ret
        
